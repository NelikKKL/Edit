//! Real VS Code file-type icons, extracted from the actual VS Code source
//! (`extensions/theme-seti/icons/vs-seti-icon-theme.json` + `seti.woff`,
//! both MIT-licensed, from the seti-ui project). `assets/seti-icons.ttf` is
//! that same font converted from WOFF to a plain TTF so it can be embedded
//! directly (see `install_seti_font` in `fonts.rs`). This table is generated
//! from the theme JSON, not hand-written — see the comment at the bottom for
//! how, if it ever needs regenerating for a newer glyph set.

/// One file-type icon: which glyph in the embedded Seti icon font, and
/// which color to draw it in for a dark vs. a light editor theme (Seti
/// ships slightly different, better-contrast colors for each).
pub struct FileIcon {
    pub glyph: char,
    pub dark_color: (u8, u8, u8),
    pub light_color: (u8, u8, u8),
}

/// Name used both when registering the embedded font (`with_icon_fonts` in
/// `app.rs`) and when building a `FontId` to draw one of these icons
/// (`file_tree.rs`), so the two can't drift apart.
pub const FONT_NAME: &str = "seti_icons";

/// The dedicated font family the icon font is registered under — never
/// mixed into the regular text fallback chains, only ever requested
/// explicitly for drawing one of these glyphs.
pub fn font_family() -> egui::FontFamily {
    egui::FontFamily::Name(std::sync::Arc::from(FONT_NAME))
}

/// Shown for any extension not in the table below.
pub const DEFAULT_ICON: FileIcon = FileIcon {
    glyph: '\u{E023}',
    dark_color: (212, 215, 214),
    light_color: (191, 194, 193),
};

/// Looks up the icon for a lowercased file extension (no leading dot).
pub fn icon_for_extension(ext: &str) -> &'static FileIcon {
    for (e, icon) in TABLE {
        if *e == ext {
            return icon;
        }
    }
    &DEFAULT_ICON
}

